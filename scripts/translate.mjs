#!/usr/bin/env node
// drawio-mcp-server translation pipeline.
//
// Subcommands:
//   locales                      Translate missing keys:
//                                packages/drawio-mcp-extension/public/_locales/en/messages.json
//                                -> <lang>/messages.json (existing keys untouched)
//   docs [files...]              Translate English docs to <name>.<lang>.md
//                                (default: README, TOOLS, CONFIG, TROUBLESHOOTING)
//   --check                      CI mode: no API call. Verifies locale key parity
//                                and that each registered doc has its translated
//                                counterpart with the snapshot banner.
//
// Flags: --lang zh-CN (default), --model <id>, --dry-run.
//
// Provider: Anthropic Messages API. Translating modes require ANTHROPIC_API_KEY
// (ANTHROPIC_BASE_URL may point at a compatible gateway). --check needs no key.
// Tool descriptions, MCP error strings, and plugin command prompts are
// deliberately NOT part of this pipeline (agent-facing, English kept).

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const LOCALES_DIR = join(
  ROOT,
  "packages/drawio-mcp-extension/public/_locales",
);
const SOURCE_LOCALE = "en";
const SOURCE_DOCS = [
  "README.md",
  "TOOLS.md",
  "CONFIG.md",
  "TROUBLESHOOTING.md",
];
const BANNER_TEXT =
  "This page is a machine-translated snapshot of the English original. The " +
  "English version is canonical; translations are regenerated by " +
  "`pnpm translate` and may lag recent changes.";

function parseArgs(argv) {
  const args = {
    check: false,
    dryRun: false,
    lang: process.env.LOCALE_TARGET || "zh-CN",
    model: process.env.ANTHROPIC_MODEL || "claude-sonnet-5-5",
    positional: [],
  };
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === "--check") args.check = true;
    else if (argv[i] === "--dry-run") args.dryRun = true;
    else if (argv[i] === "--lang") args.lang = argv[++i];
    else if (argv[i] === "--model") args.model = argv[++i];
    else args.positional.push(argv[i]);
  }
  return args;
}

function requireApiKey() {
  const apiKey = process.env.ANTHROPIC_API_KEY;
  if (!apiKey) {
    console.error(
      "translate: ANTHROPIC_API_KEY is not set; translating modes need it. " +
        "--check runs without the key.",
    );
    process.exit(1);
  }
  return apiKey;
}

async function anthropic(apiKey, model, body) {
  const base = process.env.ANTHROPIC_BASE_URL || "https://api.anthropic.com";
  const response = await fetch(`${base}/v1/messages`, {
    method: "POST",
    headers: {
      "content-type": "application/json",
      "x-api-key": apiKey,
      "anthropic-version": "2023-06-01",
    },
    body: JSON.stringify({ model, max_tokens: 32000, ...body }),
  });
  if (!response.ok) {
    const detail = await response.text().catch(() => "");
    throw new Error(`Anthropic API ${response.status}: ${detail.slice(0, 300)}`);
  }
  const data = await response.json();
  const text = (data.content || [])
    .filter((block) => block.type === "text")
    .map((block) => block.text)
    .join("");
  if (!text) throw new Error("Anthropic API returned no text content");
  return text;
}

async function withRetries(label, attempt) {
  let lastError;
  for (let tries = 0; tries < 3; tries++) {
    try {
      return await attempt();
    } catch (error) {
      lastError = error;
      if (tries < 2) {
        const delay = 2000 * (tries + 1);
        console.warn(`translate: ${label} failed (${error.message}); retrying in ${delay}ms`);
        await new Promise((res) => setTimeout(res, delay));
      }
    }
  }
  throw lastError;
}

function toDirName(locale) {
  return locale.replace(/-/g, "_");
}

function localeName(locale) {
  const names = { "zh-CN": "Simplified Chinese (zh-CN)" };
  return names[locale] || locale;
}

const PLACEHOLDER_RE = /\$(?:\d+|\w+\$)|%%\w+%%/g;
function assertPlaceholdersPreserved(sourceMessage, translatedMessage, key) {
  const held = (message) => new Set(message.match(PLACEHOLDER_RE) || []);
  const translatedHeld = held(translatedMessage);
  for (const placeholder of held(sourceMessage)) {
    if (!translatedHeld.has(placeholder)) {
      throw new Error(
        `translate: key "${key}" lost placeholder ${placeholder} in translation; refusing to write`,
      );
    }
  }
}

function prettyJson(value) {
  return `${JSON.stringify(value, null, 4)}\n`;
}

function parseJsonObject(raw) {
  const start = raw.indexOf("{");
  const end = raw.lastIndexOf("}");
  if (start === -1 || end === -1) throw new Error("provider response has no JSON object");
  return JSON.parse(raw.slice(start, end + 1));
}

async function runLocales(args) {
  const sourcePath = join(LOCALES_DIR, SOURCE_LOCALE, "messages.json");
  const targetPath = join(LOCALES_DIR, toDirName(args.lang), "messages.json");
  const source = readJson(sourcePath);
  const existing = existsSync(targetPath) ? readJson(targetPath) : {};
  const missingInTarget = Object.keys(source).filter((key) => !(key in existing));
  const staleKeys = Object.keys(existing).filter((key) => !(key in source));

  if (missingInTarget.length === 0 && staleKeys.length === 0) {
    console.log(
      `translate: ${args.lang} catalog is complete (${Object.keys(existing).length} keys)`,
    );
    return;
  }
  if (staleKeys.length > 0) {
    console.warn(
      `translate: ${args.lang} catalog has keys absent from en; dropping: ${staleKeys.join(", ")}`,
    );
  }
  if (missingInTarget.length === 0) {
    if (!args.dryRun) writeFileSync(targetPath, prettyJson({}));
    console.log("translate: no missing keys, catalog rewritten without stale keys");
    return;
  }

  console.log(
    `translate: ${missingInTarget.length} missing keys -> ${targetPath}`,
  );
  if (args.dryRun) {
    console.log(missingInTarget.join("\n"));
    return;
  }
  const apiKey = requireApiKey();

  const payload = Object.fromEntries(
    missingInTarget.map((key) => [key, source[key].message]),
  );
  const prompt = [
    "Translate the JSON catalog of UI strings for a browser extension from English into natural, concise, technically correct " + localeName(args.lang) + ".",
    "Keep product and technology names (Draw.io, MCP, WebSocket, iframe, URL, Chrome, MV3, Firefox) untranslated.",
    "Keep UI strings short (labels/buttons, no punctuation noise); sentences stay complete.",
    "Preserve positional placeholders like $1/$2 exactly as in the source.",
    "Respond with ONLY a JSON object mapping each key to the translated string (same keys, no commentary, no code fences).",
    `Catalog: ${JSON.stringify(payload)}`,
  ].join("\n");
  const raw = await withRetries("locales", () =>
    anthropic(apiKey, args.model, {
      system: "You are a professional localization engineer. You output exactly one JSON object and nothing else.",
      messages: [{ role: "user", content: prompt }],
    }),
  );
  const translations = parseJsonObject(raw);
  for (const key of missingInTarget) {
    if (!translations[key]) {
      throw new Error(`translate: provider returned no translation for key "${key}"`);
    }
    assertPlaceholdersPreserved(source[key].message, translations[key], key);
  }

  const nextCatalog = { ...existing };
  for (const key of staleKeys) delete nextCatalog[key];
  for (const key of missingInTarget) {
    nextCatalog[key] = { message: translations[key] };
  }
  writeFileSync(targetPath, prettyJson(nextCatalog));
  console.log(`translate: wrote catalog to ${targetPath}`);
  return;
}

async function runDocs(args, files) {
  const apiKey = args.dryRun ? undefined : requireApiKey();
  let hadFailure = false;
  for (const file of files) {
    const sourcePath = join(ROOT, file);
    if (!existsSync(sourcePath)) {
      console.error(`translate docs: source not found: ${file}`);
      hadFailure = true;
      continue;
    }
    const outPath = sourcePath.replace(/\.md$/, `.${args.lang}.md`);
    const source = readFileSync(sourcePath, "utf-8");
    console.log(`translate docs: ${file} -> ${outPath.replace(`${ROOT}/`, "")}`);
    if (args.dryRun) continue;

    const prompt = [
      `Translate the following English documentation file into natural, technically correct ${localeName(args.lang)}.`,
      "Keep product and technology names (drawio-mcp-server, drawio, Draw.io, MCP, WebSocket, Node.js, Zed, Claude, Codex, npx, pnpm) untranslated.",
      "Preserve the exact Markdown structure:",
      "- Every heading level, list item, table, and blockquote survives in the same order.",
      "- Fenced code blocks, inline code, URLs, link targets, link paths, HTML, and JSON stay BYTE-IDENTICAL (never translate code or config snippets).",
      "- Keep literal filenames like README.md, TOOLS.md, .zh-CN.md untouched.",
      "Output the translated Markdown only, no commentary, no code fences around the document.",
      "",
      source,
    ].join("\n");
    let translated;
    try {
      translated = await withRetries(file, () =>
        anthropic(apiKey, args.model, {
          system: "You are a professional technical documentation translator. You output only the translated Markdown document.",
          messages: [{ role: "user", content: prompt }],
        }),
      );
    } catch (error) {
      console.error(`translate docs: ${file} failed: ${error.message}`);
      hadFailure = true;
      continue;
    }
    writeFileSync(outPath, `> ${BANNER_TEXT}\n\n${translated.trim()}\n`);
    console.log(`translate docs: wrote ${outPath.replace(`${ROOT}/`, "")}`);
  }
  if (hadFailure) process.exit(1);
}

function checkLocales(args) {
  const sourcePath = join(LOCALES_DIR, SOURCE_LOCALE, "messages.json");
  const targetPath = join(LOCALES_DIR, toDirName(args.lang), "messages.json");
  if (!existsSync(targetPath)) {
    console.error(`translate --check: missing catalog ${targetPath}`);
    return false;
  }
  const source = readJson(sourcePath);
  const target = readJson(targetPath);
  const missingInTarget = Object.keys(source).filter((key) => !(key in target));
  const missingInSource = Object.keys(target).filter((key) => !(key in source));
  const missingMessages = Object.keys(target).filter((key) => !target[key]?.message);
  if (
    missingInTarget.length > 0 ||
    missingInSource.length > 0 ||
    missingMessages.length > 0
  ) {
    console.error(
      `translate --check: catalog drift for ${args.lang}: missing-in-target=[${missingInTarget}] missing-in-source=[${missingInSource}] empty-messages=[${missingMessages}]`,
    );
    return false;
  }
  return true;
}

function checkDocs(args) {
  let failed = false;
  for (const file of SOURCE_DOCS) {
    const outPath = join(ROOT, file.replace(/\.md$/, `.${args.lang}.md`));
    if (!existsSync(outPath)) {
      console.error(
        `translate --check: missing translation for ${file} (${outPath.replace(`${ROOT}/`, "")})`,
      );
      failed = true;
      continue;
    }
    const content = readFileSync(outPath, "utf-8");
    if (!content.includes(BANNER_TEXT)) {
      console.error(
        `translate --check: ${outPath.replace(`${ROOT}/`, "")} lacks the snapshot banner`,
      );
      failed = true;
    }
  }
  return !failed;
}

function readJson(path) {
  return JSON.parse(readFileSync(path, "utf-8"));
}

const args = parseArgs(process.argv.slice(2));
const [command, ...rest] = args.positional;

if (args.check) {
  const ok = checkLocales(args) && checkDocs(args);
  if (ok) console.log("translate --check: ok");
  process.exit(ok ? 0 : 1);
}

if (command === "locales") {
  await runLocales(args);
} else if (command === "docs") {
  const files = rest.length > 0 ? rest : SOURCE_DOCS;
  await runDocs(args, files);
} else {
  console.error(
    "Usage: node scripts/translate.mjs <locales|docs> [--check] [--lang zh-CN] [--model <id>] [--dry-run]",
  );
  console.error(
    "  locales: gap-fill packages/drawio-mcp-extension/public/_locales/<lang>/messages.json from en.",
  );
  console.error(
    "  docs:    translate README.md/TOOLS.md/CONFIG.md/TROUBLESHOOTING.md to <name>.<lang>.md.",
  );
  process.exit(2);
}